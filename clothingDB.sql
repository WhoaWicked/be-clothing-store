    updated_at   TIMESTAMP DEFAULT now()
);

CREATE TABLE activity_logs (
    id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      INTEGER,
    action       VARCHAR(255),
    entity_name  VARCHAR(255),
    entity_id    VARCHAR(255),
    details      JSONB,
    "timestamp"  TIMESTAMP DEFAULT now(),
